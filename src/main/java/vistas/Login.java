    private models.Usuario buscarUsuario(String username) {
    for (models.Usuario u : models.Usuario.getListaUsuario()) {
        if (u.getUserName().equalsIgnoreCase(username)) {
            return u; 
        }
    }
    return null; 
    }
    
    private void abrirMenu(models.Usuario u) {
    // Creamos la instancia pasando el usuario logueado
    Menu ventanaPrincipal = new Menu(u); 
    ventanaPrincipal.setVisible(true);
    
    // Cerramos el Login
    this.dispose(); 
    }
