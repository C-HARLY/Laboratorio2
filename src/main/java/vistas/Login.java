    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        //capturamos el username y la password
        String user = txtUser.getText().trim();
        String pass = new String(txtPass.getPassword()).trim();
        
        //llamamos al metodo para verificar las credenciales
        String resultado = Usuario.login(user, pass);
        
        //casos segun la condicion que se cumpla 
        switch(resultado){
           case "LOGEADO EXITOSAMENTE":
            
            models.Usuario userLogueado = buscarUsuario(user); 

            if (userLogueado.isDebeCambiarPass()) {
                JOptionPane.showMessageDialog(this, "Por seguridad, debe cambiar su contraseña de primer ingreso.");

               
                vistas.ReinicioClave dialog = new vistas.ReinicioClave(this, true, userLogueado.getUserName());
                dialog.setLocationRelativeTo(null);
                dialog.setVisible(true);

                
                if (!userLogueado.isDebeCambiarPass()) {
                    abrirMenu(userLogueado);
                }
            } else {
                
                abrirMenu(userLogueado);
            }
            break;
            case "USUARIO BLOQUEADO":
                JOptionPane.showMessageDialog(this, "EL USUARIO SE ENCUENTRA BLOQUEADO CONTACTE A SU ADMINISTRADOR");
                break;
            case "CONTRASEÑA INCORRECTA":
                JOptionPane.showMessageDialog(this, "LA CONTRASEÑA ES INCORRECTA. INTENTE NUEVAMENTE");
                break;
            case "EL USUARIO SE ENCUENTRA INACTIVO":
                JOptionPane.showMessageDialog(this, "EL USUARIO SE ENCUENTRA INACTIVO");
                break;
                
            default:
                JOptionPane.showMessageDialog(this, "EL USUARIO NO EXISTE");
                break;
        }
        
            
        
    }//GEN-LAST:event_btnLoginActionPerformed

