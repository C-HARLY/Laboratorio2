    private boolean validarComplejidad(String password) {
    // Verificación de longitud mínima
    if (password.length() < 13) return false;

    boolean tieneMayuscula = false;
    boolean tieneEspecial = false;
    
    // Definición de caracteres especiales permitidos
    String caracteresEspeciales = "!@#$%^&*()-_=+[]{};:,.<>/?";

    for (int i = 0; i < password.length(); i++) {
        char c = password.charAt(i);
        
        if (Character.isUpperCase(c)) {
            tieneMayuscula = true;
        } else if (caracteresEspeciales.contains(String.valueOf(c))) {
            tieneEspecial = true;
        }
        
        // Optimización: si ya cumple ambas condiciones, se puede retornar true
        if (tieneMayuscula && tieneEspecial) return true;
    }

    return tieneMayuscula && tieneEspecial;
}
    
