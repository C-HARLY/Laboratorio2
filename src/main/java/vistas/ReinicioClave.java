    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // Extracción de las cadenas de caracteres de los componentes JPasswordField
    String pass1 = new String(txtNuevaPass.getPassword());
    String pass2 = new String(txtConfirmarPass.getPassword());

    // 1. Validación de campos vacíos
    if (pass1.isEmpty() || pass2.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 2. Validación de coincidencia física
    if (!pass1.equals(pass2)) {
        JOptionPane.showMessageDialog(this, "Las contraseñas no coinciden.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 3. Validación de complejidad técnica (13 caracteres, mayúscula, especial)
    if (!validarComplejidad(pass1)) {
        JOptionPane.showMessageDialog(this, 
            "La contraseña debe cumplir con:\n- Mínimo 13 caracteres.\n- Al menos una letra mayúscula.\n- Al menos un carácter especial.", 
            "Seguridad Insuficiente", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 4. Persistencia en la lista global de objetos Usuario
    for (models.Usuario u : models.Usuario.getListaUsuario()) {
    if (u.getUserName().equals(this.userNameDestino)) {
        u.setPassword(pass1);              
        u.setDebeCambiarPass(false);       
        u.setIntentos(0);                  
        break;
    }
}

    JOptionPane.showMessageDialog(this, "Contraseña actualizada exitosamente.");
    this.dispose(); // Cierre del JDialog tras la operación exitosa
    }//GEN-LAST:event_btnGuardarActionPerformed

